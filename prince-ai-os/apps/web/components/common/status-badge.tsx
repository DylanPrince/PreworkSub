import { Badge } from "@/components/ui/badge";

const TONES = {
  open: "neutral",
  queued: "info",
  running: "primary",
  succeeded: "success",
  failed: "danger",
  cancelled: "warning",
  waiting_approval: "warning",
  active: "success",
  disabled: "neutral",
  archived: "neutral",
  // Business module stages.
  planning: "neutral",
  approved: "success",
  ended: "neutral",
  idea: "neutral",
  drafting: "info",
  review: "warning",
  published: "success",
  researching: "info",
  sourcing: "info",
  ready: "primary",
  listed: "success",
  retired: "neutral",
  specification: "info",
  building: "primary",
  testing: "info",
  launched: "success",
  paused: "warning",
  todo: "neutral",
  in_progress: "primary",
  done: "success",
} as const;

export function StatusBadge({ status }: { status: string }) {
  const tone = TONES[status as keyof typeof TONES] ?? "neutral";
  return (
    <Badge tone={tone}>
      {status === "running" && (
        <span aria-hidden className="size-1.5 animate-pulse rounded-full bg-current" />
      )}
      {status.replaceAll("_", " ")}
    </Badge>
  );
}

/** Distinguishes real Claude output from mock placeholders wherever a run is shown. */
export function ProviderBadge({ provider }: { provider: string }) {
  if (provider === "mock")
    return (
      <Badge tone="warning" title="Generated locally without an AI model. Not real analysis.">
        Mock output
      </Badge>
    );
  if (provider === "anthropic")
    return (
      <Badge tone="info" title="Generated by the Claude API (billed usage).">
        Claude
      </Badge>
    );
  return <Badge tone="neutral">{provider}</Badge>;
}
